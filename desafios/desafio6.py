lado1 = float(input("Digite um número para ser a largura de um retângulo (em cm): "))
lado2 = float(input("Digite um número para ser o comprimento de um retângulo (em cm): "))

area = lado1 * lado2
perimetro = lado1 + lado1 + lado2 + lado2

print(f"A área do retângulo é de {area}cm²")
print(f"O perímetro do retângulo é de {perimetro}cm")
