n1 = float(input("Digite um número: "))
antecessor = n1 - 1
sucessor = n1 + 1
dobro = n1 * 2
metade = n1 / 2

print(f"O antecessor do seu número é {antecessor}")
print(f"O sucessor do seu número é {sucessor}")
print(f"O dobro do seu número é {dobro}")
print(f"A metade do número, o qual vossa senhoria escolheu, pode ser declarado por {metade}")